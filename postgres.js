export async function initDatabase() {
  for (const sql of schema) await pool.query(sql);
  await pool.query('SELECT 1');
  console.log("PostgreSQL inicializado");
}
function normalize(sql) {
  let n = 0;
  return sql
    .replace(/\?/g, () => '$' + (++n))
    .replace(/DATE\('now',\s*'-6 days'\)/gi, "TO_CHAR(CURRENT_DATE - INTERVAL '6 days', 'YYYY-MM-DD')")
     .replace(/DATE\('now'\)/gi, 'CURRENT_DATE')
    .replace(/datetime\('now',\s*'-1 day'\)/gi, "TO_CHAR(NOW() - INTERVAL '1 day', 'YYYY-MM-DD HH24:MI:SS')")
    .replace(/datetime\((\w+\.\w+)\)/gi, '$1')
    .replace(/\(julianday\(([^)]+)\)\s*-\s*julianday\(([^)]+)\)\)/gi, '(EXTRACT(EPOCH FROM ($1::timestamp - $2::timestamp)) / 86400.0)')
    .replace(/\bDATE\((\w+(?:\.\w+)?)\)/gi, 'DATE($1::timestamp)')
     .replace(/COUNT\(\*\)/gi, 'COUNT(*)::int')
     .replace(/COUNT\(DISTINCT (\w+)\)/gi, 'COUNT(DISTINCT $1)::int');
}
function execute(kind, sql, args) {
  const callback = typeof args[args.length - 1] === 'function' ? args.pop() : null;
  const params = args[0] ?? [];
  const values = Array.isArray(params) ? params : [];
  let statement = normalize(sql);
  if (kind === 'run' && /^\s*INSERT\b/i.test(statement) && !/\bRETURNING\b/i.test(statement)) statement += ' RETURNING id';
  const task = pool.query(statement, values);
  if (callback) task.then(result => {
    if (kind === 'run') callback.call({ lastID: result.rows[0]?.id, changes: result.rowCount }, null);
    else callback(null, kind === 'get' ? result.rows[0] : result.rows);
  }).catch(err => callback(err));
  else task.catch(err => console.error('Error PostgreSQL:', err.message));
  return task;
}
export const db = {
  run(sql, ...args) { return execute('run', sql, args); },
  get(sql, ...args) { return execute('get', sql, args); },
  all(sql, ...args) { return execute('all', sql, args); },
  async query(sql, params = []) { return (await pool.query(normalize(sql), params)).rows; }
};

export async function withTransaction(work) {
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    const result = await work((sql, params=[]) => client.query(sql, params));
    await client.query("COMMIT");
    return result;
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}
