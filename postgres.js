import pg from "pg";
const { Pool } = pg;
if (!process.env.DATABASE_URL) throw new Error("DATABASE_URL es obligatoria para PostgreSQL");
const pool = new Pool({ connectionString: process.env.DATABASE_URL, max: 10 });
const schema = [
  `CREATE TABLE IF NOT EXISTS mensajes (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, numero TEXT, mensaje TEXT, tipo TEXT, fecha TEXT, archivo TEXT, mime_type TEXT, es_multimedia INTEGER DEFAULT 0)`,
  `CREATE TABLE IF NOT EXISTS clientes (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, numero TEXT UNIQUE, nombre TEXT, etiqueta TEXT DEFAULT 'nuevo', ultima_interaccion TEXT, archivado INTEGER DEFAULT 0, nota TEXT DEFAULT '')`,
  `CREATE TABLE IF NOT EXISTS respuestas (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, texto TEXT NOT NULL)`,
  `CREATE TABLE IF NOT EXISTS recordatorios (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, numero TEXT NOT NULL, fecha_recordatorio TEXT NOT NULL, mensaje TEXT, completado INTEGER DEFAULT 0, activo INTEGER DEFAULT 1, created_at TEXT DEFAULT CURRENT_TIMESTAMP)`,
  `ALTER TABLE recordatorios ADD COLUMN IF NOT EXISTS activo INTEGER DEFAULT 1`
];
export async function initDatabase() {
  for (const sql of schema) await pool.query(sql);
  console.log("PostgreSQL inicializado");
}
function normalize(sql) {
  let n = 0;
  return sql
    .replace(/\?/g, () => '$' + (++n))
    .replace(/DATE\('now',\s*'-6 days'\)/gi, "CURRENT_DATE - INTERVAL '6 days'")
    .replace(/DATE\('now'\)/gi, 'CURRENT_DATE')
    .replace(/datetime\('now',\s*'-1 day'\)/gi, "NOW() - INTERVAL '1 day'")
    .replace(/datetime\((\w+\.\w+)\)/gi, '$1')
    .replace(/julianday\(([^)]+)\)\s*-\s*julianday\(([^)]+)\)/gi, '(EXTRACT(EPOCH FROM ($1::timestamp - $2::timestamp)) / 86400.0)')
    .replace(/\bDATE\((\w+(?:\.\w+)?)\)/gi, 'DATE($1::timestamp)')
    .replace(/COUNT\(\*\)/gi, 'COUNT(*)::int')
    .replace(/COUNT\(DISTINCT (\w+)\)/gi, 'COUNT(DISTINCT $1)::int');
}
function execute(kind, sql, args) {
  const callback = typeof args[args.length - 1] === 'function' ? args.pop() : null;
  const params = args[0] ?? [];
  const values = Array.isArray(params) ? params : [];
  let statement = normalize(sql);
  if (kind === 'run' && /^\s*INSERT\b/i.test(statement) && !/\bRETURNING\b/i.test(statement)) statement += ' RETURNING id';
  const task = pool.query(statement, values);
  if (callback) task.then(result => {
    if (kind === 'run') callback.call({ lastID: result.rows[0]?.id, changes: result.rowCount }, null);
    else callback(null, kind === 'get' ? result.rows[0] : result.rows);
  }).catch(err => callback(err));
  else task.catch(err => console.error('Error PostgreSQL:', err.message));
  return task;
}
export const db = {
  run(sql, ...args) { return execute('run', sql, args); },
  get(sql, ...args) { return execute('get', sql, args); },
  all(sql, ...args) { return execute('all', sql, args); },
  async query(sql, params = []) { return (await pool.query(normalize(sql), params)).rows; }
};
